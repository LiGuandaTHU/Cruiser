def yamlfile2name(attacker_config_filename):
    return attacker_config_filename.split("/")[-1][:-5]

def pmlfile2name(attacker_config_filename):
    return attacker_config_filename.split("/")[-1][:-4]

def checkAttackerInSenario(model, attacker_name):
    for line in model:
        temp = line.strip().split(" ")
        if "proctype" in temp:
            index = temp.index("proctype") + 1
            if temp[index].startswith(attacker_name + "("):
                return True
    return False

def checkAttackerEnd(attacker_config_file):
    with open(attacker_config_file, "r") as f:
        attacker_cfg = yaml.safe_load(f)
    return attacker_cfg["end"]

def constructAttackModel(model, attacker_name_to_file, is_attacker_contained_in_senario, attackers_needend):
    nowAttackerName = None
    newModel = []
    tag = "CruiserPoint:"

    if len(attackers_needend) > 0:
        newModel.append("// Generated by Cruiser: Ending Variables for Labeling the Ending of Attackers' Attacks")
        for attacker_name in attackers_needend:
            newModel.append(f"bool is_{attacker_name}_end = false;")
        newModel.append("")

    for line in model:
        newModel.append(line)
        temp = line.strip().split(" ")
        if "proctype" in temp and nowAttackerName is None:
            index = temp.index("proctype") + 1
            for attacker_name in attacker_name_to_file.keys():
                if temp[index].startswith(attacker_name + "("):
                    nowAttackerName = attacker_name
                    break
        if nowAttackerName is not None:
            if temp[0].startswith(tag):
                attacker_config_file = attacker_name_to_file[nowAttackerName]
                attacker_code = GenerateAttackerCode(attacker_config_file, True)
                newModel.extend(attacker_code)
                nowAttackerName = None
                continue
    for attacker_name, contained in is_attacker_contained_in_senario.items():
        if not contained:
            attacker_config_file = attacker_name_to_file[attacker_name]
            attacker_code = GenerateAttackerCode(attacker_config_file, False)
            newModel.extend(attacker_code)
    return newModel

